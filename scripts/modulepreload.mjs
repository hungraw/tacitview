// Lists every module reachable from src/main.js and (with --write) puts a <link rel="modulepreload"> for each into
// index.html, so the browser fetches the whole graph at once instead of discovering it a level at a time.
// test/offline.cjs checks the list in index.html is current; run `node scripts/modulepreload.mjs --write` after
// adding or removing an import.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export function moduleGraph(entries = [join(root, 'src/main.js')]) {
  const seen = new Set();
  const walk = (file) => {
    if (seen.has(file)) return;
    seen.add(file);
    const src = readFileSync(file, 'utf8');
    for (const m of src.matchAll(/^\s*(?:import|export)\s[^;]*?from\s+['"](\.{1,2}\/[^'"]+)['"]/gm)) walk(resolve(dirname(file), m[1]));
  };
  for (const entry of entries) walk(entry);
  for (const entry of entries) seen.delete(entry); // each entry is a <script> itself
  return [...seen].map((f) => `/${relative(root, f)}`).sort();
}
export const preloadBlock = (list) => `<!-- modulepreload:start -->\n${list.map((p) => `  <link rel="modulepreload" href="${p}">`).join('\n')}\n  <!-- modulepreload:end -->`;

// src/early.js: one self-contained classic script (no imports, so it never waits for other files) that starts the
// current page's data requests while the app's modules load. Its route parser and path builder are the app's own
// functions (router.js, data/paths.js) copied in as source, and its per-page lists come from layouts.js and the
// sections' sources, so it cannot drift: test/offline.cjs checks the file equals this output.
export async function earlyScript() {
  const router = await import('../src/router.js');
  const { detailPath } = await import('../src/data/paths.js');
  const { LAYOUTS } = await import('../src/layouts.js');
  const { SECTIONS } = await import('../src/sections/index.js');
  const { SOURCES } = await import('../src/data/api.js');
  const { PAGE_MODULES } = await import('../src/page-modules.js');
  // For each view: its page module(s) and their imports that the app's main graph does not already load.
  const main = new Set(moduleGraph());
  const pageMods = {};
  for (const [view, entry] of Object.entries(PAGE_MODULES)) {
    const files = (view === 'footprint' ? entry.map((e) => e[0]) : [entry[0]]).map((f) => join(root, 'src', f));
    pageMods[view] = [...new Set([...files.map((f) => `/${relative(root, f)}`), ...moduleGraph(files)])].filter((m) => !main.has(m)).sort();
  }
  const pages = {};
  for (const [page, layout] of Object.entries(LAYOUTS)) {
    const ids = layout.rows.flatMap((r) => r.cards.map((c) => c[0]));
    pages[page] = [...new Set(ids.flatMap((id) => SECTIONS.find((x) => x.id === id)?.sources || []))].map((n) => SOURCES[n][0]);
  }
  const table = (t) => `{\n${Object.entries(t).map(([k, v]) => `    ${JSON.stringify(k)}: { view: ${JSON.stringify(v.view)}, valid: ${v.valid.toString()} },`).join('\n')}\n  }`;
  return `// Generated by scripts/modulepreload.mjs --write. Do not edit: change router.js, data/paths.js, layouts.js or the sections.
// Starts the current page's data requests at once, while the app's modules are still loading; data/api.js uses the answers.
(() => {
  const isBtcAddress = ${router.isBtcAddress.toString()};
  const LIVE = new Set(${JSON.stringify([...router.LIVE])});
  const DETAIL = ${table(router.DETAIL)};
  const LISTS = ${table(router.LISTS)};
  ${router.parseRoute.toString()}
  ${detailPath.toString()}
  const PAGE_PATHS = ${JSON.stringify(pages)};
  const PAGE_MODULES = ${JSON.stringify(pageMods)};
  let route; try { route = parseRoute(location.hash); } catch { return; } // a malformed URL: the app shows the error page
  const paths = route.kind === 'live' ? PAGE_PATHS[route.page] || [] : route.kind === 'detail' || route.kind === 'list' ? [detailPath(route.view, route.id)] : [];
  const early = (window.__tacitEarly = window.__tacitEarly || {});
  for (const p of paths) early[p] = { at: Date.now(), data: fetch('/api' + p, { headers: { accept: 'application/json' }, cache: 'no-store' }).then((r) => (r.ok ? r.json() : null)).catch(() => null) };
  // The page's own code (loaded on demand by the app), fetched now too.
  for (const href of PAGE_MODULES[route.view] || []) { const l = document.createElement('link'); l.rel = 'modulepreload'; l.href = href; document.head.append(l); }
})();
`;
}

// index.html carries the stylesheet and early.js inline, so the page paints and its data requests start as soon as the
// HTML arrives, without waiting on other files. Their SHA-256 hashes go into the Content-Security-Policy
// (server/inline-hashes.json for the dev server, vercel.json for production): nothing else inline may run.
export const cspHash = (text) => `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;
export function inlineBlocks() {
  const css = readFileSync(join(root, 'styles.css'), 'utf8'), early = readFileSync(join(root, 'src/early.js'), 'utf8');
  return {
    style: `<!-- inline-css:start --><style>${css}</style><!-- inline-css:end -->`,
    script: `<!-- inline-early:start --><script>${early}</script><!-- inline-early:end -->`,
    hashes: { style: cspHash(css), script: cspHash(early) },
  };
}

if (process.argv.includes('--write')) {
  writeFileSync(join(root, 'src/early.js'), await earlyScript());
  {
    const { style, script, hashes } = inlineBlocks();
    let html = readFileSync(join(root, 'index.html'), 'utf8');
    html = html.replace(/<!-- inline-css:start -->[\s\S]*?<!-- inline-css:end -->|<link rel="stylesheet" href="\/styles\.css[^>]*>/, () => style);
    html = html.replace(/<!-- inline-early:start -->[\s\S]*?<!-- inline-early:end -->|<script async[^>]*src="\/src\/early\.js[^>]*><\/script>/, () => script);
    writeFileSync(join(root, 'index.html'), html);
    writeFileSync(join(root, 'server/inline-hashes.json'), `${JSON.stringify(hashes, null, 2)}\n`);
    const { SECURITY_HEADERS } = (await import('node:module')).createRequire(import.meta.url)('../server/security-headers.cjs');
    const vercel = JSON.parse(readFileSync(join(root, 'vercel.json'), 'utf8'));
    vercel.headers[0].headers = Object.entries(SECURITY_HEADERS).map(([key, value]) => ({ key, value })); // every security header, as the dev server sends them
    writeFileSync(join(root, 'vercel.json'), `${JSON.stringify(vercel, null, 2)}\n`);
  }
  const path = join(root, 'index.html');
  const html = readFileSync(path, 'utf8');
  const block = preloadBlock(moduleGraph());
  const next = /<!-- modulepreload:start -->[\s\S]*?<!-- modulepreload:end -->/.test(html)
    ? html.replace(/<!-- modulepreload:start -->[\s\S]*?<!-- modulepreload:end -->/, block)
    : html.replace(/(\s*)(<script type="module")/, `$1${block}$1$2`);
  writeFileSync(path, next);
  console.log(`${moduleGraph().length} modules preloaded`);
}
